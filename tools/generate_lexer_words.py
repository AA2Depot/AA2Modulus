"""Generate the word lists of the website's ``aa2m`` Pygments lexer

Writes tools/pygments-aa2m/pygments_aa2m/words.py from the source lexicon and
the editor catalog: one constant per lexicon group, the literal-form patterns
and the built-in names. Receiver built-ins (``<card>.X``) contribute their
member name. With --check, compares instead of writing.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aa2modulus.app.editor_catalog.document import editor_catalog
from aa2modulus.syntax.lexicon import source_lexicon

TARGET = ROOT / "tools/pygments-aa2m/pygments_aa2m/words.py"
HEADER = '''\
"""Word lists of the ``aa2m`` lexer.

Generated by tools/generate_lexer_words.py. Do not edit by hand.
"""

from __future__ import annotations
'''
FUNCTION_KINDS = frozenset({"action", "expression"})
CONSTANT_KINDS = frozenset({"event", "named_constant"})
RECEIVER = re.compile(r"<\w+>\.(\w+)")


def render(entries: Iterable[Mapping[str, Any]]) -> str:
    lexicon = source_lexicon()
    functions: set[str] = set()
    constants: set[str] = set()
    members: set[str] = set()
    for entry in entries:
        for name in (entry["name"], *entry["aliases"]):
            if receiver := RECEIVER.fullmatch(name):
                members.add(receiver.group(1))
            elif entry["kind"] in FUNCTION_KINDS:
                functions.add(name)
            elif entry["kind"] in CONSTANT_KINDS:
                constants.add(name)
            else:
                raise ValueError(f"unknown entry kind {entry['kind']!r}")

    blocks = [HEADER]
    for group, literals in lexicon.groups:
        blocks.append(_frozenset(_constant_name(group), literals))
    blocks.append(_mapping("PATTERNS", dict(lexicon.patterns)))
    blocks.append(_frozenset("FUNCTIONS", functions))
    blocks.append(_frozenset("CONSTANTS", constants))
    blocks.append(_frozenset("MEMBERS", members))
    return "\n".join(blocks)


def _constant_name(group: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", group).upper()


def _frozenset(name: str, values: Iterable[str]) -> str:
    items = "".join(f"        {json.dumps(value)},\n" for value in sorted(values))
    return f"{name} = frozenset(\n    {{\n{items}    }}\n)\n"


def _mapping(name: str, values: Mapping[str, str]) -> str:
    items = "".join(
        f"    {json.dumps(key)}: {json.dumps(values[key])},\n" for key in sorted(values)
    )
    return f"{name} = {{\n{items}}}\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the aa2m lexer's word lists")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    arguments = parser.parse_args()

    document, _ = editor_catalog()
    text = render(document["entries"])
    relative = TARGET.relative_to(ROOT).as_posix()

    if arguments.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            parser.exit(1, f"lexer word lists are not current: {relative}\n")
        print(f"verified {relative}")
        return

    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {relative}")


if __name__ == "__main__":
    main()
