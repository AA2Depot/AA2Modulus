"""Generate the website's built-ins pages from the editor catalog

Writes docs/reference/builtins/: one page per entry kind and native category at
the path each entry's docPath names, an overview (index.md), a table from
AAEdit names to source names (native-names.md) and the section's navigation
(SUMMARY.md, read by literate-nav). Entries keep the editor's
built-in page text under a heading whose anchor is the entry ID. The tool owns
the folder and removes pages no entry names. With --check, compares instead of
writing.
"""

from __future__ import annotations

import argparse
import os
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aa2modulus.app.editor_catalog.document import editor_catalog
from aa2modulus.app.editor_catalog.pages import escape_markdown, sections

DOCS = ROOT / "docs"
FOLDER = DOCS / "reference/builtins"
KINDS = (
    ("event", "Events", "events"),
    ("action", "Actions", "actions"),
    ("expression", "Expressions", "expressions"),
    ("named_constant", "Named constants", "named constants"),
)
GENERATED = "<!-- Generated by tools/generate_builtins_pages.py. Do not edit by hand. -->"

INDEX = """\
---
description: Every event, action, expression and named constant a module can use.
---

{generated}

# Built-ins

Events start a trigger, actions are what it runs, expressions are the values it
reads and named constants are fixed values with a name. Each entry shows how you
write it in `.aa2m`, its parameters and an example that compiles. Entries are
grouped by the category AAEdit uses, and the native name at the end of each
entry is the label AAEdit shows. [AAEdit names](native-names.md) finds an
entry by that label. Each named constants page starts with a table by value,
for finding the constant behind a plain number in a module.
"""

NATIVE_NAMES = """\
---
description: Find the .aa2m name of a built-in from the name AAEdit shows.
---

{generated}

# AAEdit names

Every built-in by the name AAEdit shows, with the name you write in `.aa2m`.

| AAEdit name | Kind | `.aa2m` name |
| --- | --- | --- |
"""

Page = tuple[str, list[Mapping[str, Any]]]


def render(entries: list[Mapping[str, Any]]) -> dict[Path, str]:
    """Generated file path -> text."""

    index = [INDEX.format(generated=GENERATED).rstrip("\n")]
    summary = ["* [Built-ins](index.md)", "* [AAEdit names](native-names.md)"]
    files: dict[Path, str] = {}

    for kind, title, noun in KINDS:
        pages = _pages([entry for entry in entries if entry["kind"] == kind])
        index.append(f"## {title}")
        index.append(
            "\n".join(
                _link(path, category, len(listed)) for path, (category, listed) in pages.items()
            )
        )
        summary.append(f"* {title}")
        for path, (category, listed) in pages.items():
            summary.append(f"    * [{escape_markdown(category)}]({path})")
            files[FOLDER / path] = _page(
                f"{category} {noun}", listed, by_value=kind == "named_constant"
            )

    files[FOLDER / "index.md"] = "\n\n".join(index) + "\n"
    files[FOLDER / "native-names.md"] = _native_names(entries)
    files[FOLDER / "SUMMARY.md"] = "\n".join(summary) + "\n"
    return files


def _pages(entries: list[Mapping[str, Any]]) -> dict[str, Page]:
    """Page path relative to the folder -> its category and entries, by category."""

    pages: dict[str, Page] = {}
    for entry in entries:
        url = entry["docPath"].split("#", 1)[0]
        path = Path(url).relative_to("reference/builtins").as_posix() + ".md"
        pages.setdefault(path, (entry["category"] or "Other", []))[1].append(entry)
    return dict(sorted(pages.items(), key=lambda item: item[1][0].lower()))


def _native_names(entries: list[Mapping[str, Any]]) -> str:
    """One table row per entry, sorted by the AAEdit name."""

    kinds = {kind: noun.rstrip("s") for kind, _, noun in KINDS}
    rows = []
    for entry in sorted(entries, key=lambda entry: (entry["nativeName"].lower(), entry["id"])):
        path = Path(entry["docPath"].split("#", 1)[0]).relative_to("reference/builtins")
        link = f"[`{entry['name']}`]({path.as_posix()}.md#{entry['id']})"
        native = _entities(escape_markdown(entry["nativeName"]))
        rows.append(f"| {native} | {kinds[entry['kind']]} | {link} |")
    return NATIVE_NAMES.format(generated=GENERATED) + "\n".join(rows) + "\n"


def _link(path: str, category: str, count: int) -> str:
    return f"- [{escape_markdown(category)}]({path}) ({count})"


def _page(title: str, entries: list[Mapping[str, Any]], *, by_value: bool) -> str:
    """One category page; a namespace every entry shares is left out of the headings."""

    entries = sorted(entries, key=lambda entry: entry["name"].lower())
    shared = os.path.commonprefix([entry["name"] for entry in entries])
    prefix = shared[: shared.rfind(".") + 1]

    parts = [GENERATED, f"# {escape_markdown(title)}"]
    if by_value:
        parts.append(_value_table(entries))
    for entry in entries:
        heading = f"## {escape_markdown(entry['name'].removeprefix(prefix))} {{ #{entry['id']} }}"
        blocks = [heading, *sections(entry, website=None)]
        parts += [block if "```" in block else _entities(block) for block in blocks]
    return "\n\n".join(parts) + "\n"


def _value_table(entries: list[Mapping[str, Any]]) -> str:
    """Named constants sorted by value, each linked to its entry."""

    rows = []
    for entry in sorted(entries, key=lambda entry: (_value_key(entry), entry["id"])):
        link = f"[`{entry['name']}`](#{entry['id']})"
        native = _entities(escape_markdown(entry["nativeName"]))
        rows.append(f"| {_value(entry)} | {link} | {native} |")
    return "\n".join(
        [
            "## By value { #by-value }",
            "",
            "Use this table to find the constant behind a plain number in decompiled source.",
            "",
            "| Value | `.aa2m` name | AAEdit name |",
            "| --- | --- | --- |",
            *rows,
        ]
    )


def _value(entry: Mapping[str, Any]) -> str:
    """The value the signature label ends with, as in ``Constants.Room.LOCKERS: int = 8``."""

    label: str = entry["signatures"][0]["label"]
    return label.rpartition(" = ")[2]


def _value_key(entry: Mapping[str, Any]) -> tuple[int, str]:
    value = _value(entry)
    try:
        return (int(value), "")
    except ValueError:
        return (0, value)


def _entities(block: str) -> str:
    """Python-Markdown cannot backslash-escape ``<`` or ``|`` as CommonMark editors can."""

    for escaped, entity in (("\\<", "&lt;"), ("\\>", "&gt;"), ("\\|", "&#124;")):
        block = block.replace(escaped, entity)
    return block


def _relative(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate docs/reference/builtins/")
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    arguments = parser.parse_args()

    document, _ = editor_catalog()
    files = render(document["entries"])
    present = set(FOLDER.rglob("*.md")) if FOLDER.exists() else set()

    if arguments.check:
        problems = [f"missing: {_relative(path)}" for path in sorted(files.keys() - present)]
        problems += [f"extra: {_relative(path)}" for path in sorted(present - files.keys())]
        problems += [
            f"stale: {_relative(path)}"
            for path in sorted(files.keys() & present)
            if path.read_text(encoding="utf-8") != files[path]
        ]
        if problems:
            lines = "".join(f"  {problem}\n" for problem in problems)
            parser.exit(1, f"built-ins pages are not current:\n{lines}")
        print(f"verified {len(files)} files in {_relative(FOLDER)}")
        return

    for path in present - files.keys():
        path.unlink()
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files in {_relative(FOLDER)}")


if __name__ == "__main__":
    main()
